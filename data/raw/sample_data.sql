DROP TABLE IF EXISTS niiha_expenses;
DROP TABLE IF EXISTS niiha_invoices;
DROP TABLE IF EXISTS niiha_contracts;

CREATE TABLE niiha_contracts (
    contract_id VARCHAR(20) PRIMARY KEY,
    client_name VARCHAR(100),
    region VARCHAR(20),
    product_line VARCHAR(50),
    acv_usd DECIMAL(12, 2),
    discount_pct DECIMAL(5, 2),
    contract_months INT,
    payment_terms VARCHAR(20),
    approved_by VARCHAR(50),
    status VARCHAR(20)
);

CREATE TABLE niiha_invoices (
    invoice_id VARCHAR(20) PRIMARY KEY,
    contract_id VARCHAR(20),
    amount_usd DECIMAL(12, 2),
    due_date DATE,
    days_overdue INT,
    payment_status VARCHAR(20),
    FOREIGN KEY (contract_id) REFERENCES niiha_contracts(contract_id)
);

CREATE TABLE niiha_expenses (
    expense_id VARCHAR(20) PRIMARY KEY,
    department VARCHAR(50),
    category VARCHAR(50),
    city_tier VARCHAR(20),
    amount_usd DECIMAL(10, 2),
    nights_or_attendees INT,
    quarter VARCHAR(10),
    receipt_attached BOOLEAN
);

